declare(strict_types=1);

/**
 * Seed 5 announcements, 5 events and 5 ordinances designed as a test matrix.
 *
 *   php tools/seed-sample-content.php                    # seed (or update)
 *   php tools/seed-sample-content.php --with-notifications
 *   php tools/seed-sample-content.php --no-translate     # skip the one API call
 *   php tools/seed-sample-content.php --purge            # remove everything
 *   php tools/seed-sample-content.php --list             # what is seeded now
 *
 * Not a migration, deliberately. Demo content must never ride along into a
 * real deployment, and runPendingMigrations() replays every migration file on
 * every database connection — a seeder in there would re-create fifteen fake
 * barangay notices on every page load.
 *
 * ── The three safety rules this script is built around ──────────────────
 *
 * 1. Everything it writes is flagged is_sample = 1 (migration 025) and every
 *    generated image says SAMPLE across it. --purge then removes exactly
 *    these rows and their files, matched on the flag rather than guessed from
 *    titles. This is a live government notice board; a seeded storm-surge
 *    advisory that cannot be told apart from a real one is a safety problem,
 *    not a tidiness problem.
 *
 * 2. Nothing goes out. The admin save path broadcasts notifications and can
 *    fire SMS through SemaphoreSmsService — fifteen posts would mean fifteen
 *    SMS broadcasts to every registered resident. This script writes through
 *    the models directly, never the controllers, and additionally clears the
 *    Semaphore credentials from the environment for the duration of the run
 *    so that nothing reached indirectly can send either. Notifications are
 *    opt-in via --with-notifications, so that path can be tested on purpose
 *    rather than by accident.
 *
 * 3. Ordinances are legal instruments. Every sample one is prefixed [SAMPLE]
 *    in both its title and its number, its body says plainly that it is
 *    illustrative, and its PDF carries a red SAMPLE banner on page one.
 *
 * ── What it still shares with the real save path ────────────────────────
 *
 * Slugs come from generate_slug() + Model::uniqueSlug(). Bodies go through
 * PostHtml::purify() — the same configuration the admin form uses, which is
 * the point: sample #4 is deliberately full of pasted inline colours and they
 * have to be gone by the time they reach the database. Images and PDFs are
 * written through FileService::storeFetched(), so MIME sniffing, the
 * randomised filename and the delete path all get exercised too.
 */

$root = \dirname(__DIR__);
require $root . '/vendor/autoload.php';
if (class_exists(\Dotenv\Dotenv::class) && is_file($root . '/.env')) {
    \Dotenv\Dotenv::createImmutable($root)->safeLoad();
}
require $root . '/app/helpers.php';
require $root . '/config/database.php';
require __DIR__ . '/sample-content/media.php';
require __DIR__ . '/sample-content/content.php';

